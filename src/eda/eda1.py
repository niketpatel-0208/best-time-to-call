import pandas as pd, numpy as np, sys, os
pd.set_option('display.width', 250); pd.set_option('display.max_columns', 50); pd.set_option('display.max_rows', 200)
D = os.environ.get("BTC_DATA_DIR", "data")
S = os.path.dirname(os.path.abspath(__file__))
a = pd.read_csv(os.path.join(D, "Best-Time-to-Call - Call Attempts Apr-Sep 2026 - Best-Time-to-Call - Call Attempts Apr-Sep 2026.csv"),
                parse_dates=['lead_sent_time','call_start_time','vendor_response_time','lead_tbro_time'])
s = pd.read_csv(os.path.join(D, "Best-Time-to-Call - Sellers - Best-Time-to-Call - Sellers.csv"), low_memory=False)
a.to_pickle(os.path.join(S,'a.pkl')); s.to_pickle(os.path.join(S,'s.pkl'))
print(a.dtypes); print(a.isna().mean().round(4))
print("unique attempt ids", a.data_hotlead_disposition_dtlid.nunique(), len(a))
print("sellers in attempts", a.fk_glusr_usr_id.nunique(), "sellers file", len(s), s.fk_glusr_usr_id.nunique())
print("attempt sellers missing in seller file", (~a.fk_glusr_usr_id.isin(s.fk_glusr_usr_id)).sum())
print(a[['lead_sent_time','call_start_time','lead_tbro_time']].describe())
a['t'] = a.call_start_time.fillna(a.lead_sent_time)
a['month'] = a.t.dt.to_period('M')
print("\n== disposition x month (counts)"); print(pd.crosstab(a.month, a.disposition_label, margins=True))
print("\n== disposition x month (row %)"); print((pd.crosstab(a.month, a.disposition_label, normalize='index')*100).round(1))
print("\n== status x disposition"); print(pd.crosstab(a.lead_call_status, a.disposition_label))
print("\n== bot version"); print(a.lead_bot_version.value_counts(dropna=False).head(20))
print((pd.crosstab(a.lead_bot_version.fillna('NA'), a.disposition_label, normalize='index')*100).round(1).assign(n=a.lead_bot_version.fillna('NA').value_counts()).sort_values('n',ascending=False).head(15))
print("\n== bot version x month"); print(pd.crosstab(a.lead_bot_version.fillna('NA'), a.month).loc[lambda x: x.sum(1)>2000])
print("\n== redis bucket"); print((pd.crosstab(a.redis_bucket, a.disposition_label, normalize='index')*100).round(1).assign(n=a.redis_bucket.value_counts()).sort_values('n',ascending=False))
print("\n== bucket x month"); print(pd.crosstab(a.redis_bucket, a.month))
print("\n== attempt count dist"); print(a.call_attempt_count.value_counts().sort_index().head(25))
print((pd.crosstab(a.call_attempt_count.clip(upper=10), a.disposition_label, normalize='index')*100).round(1).assign(n=a.call_attempt_count.clip(upper=10).value_counts()))
print("\n== duration by disposition"); print(a.groupby('disposition_label').lead_call_duration.describe())
print("\n== meeting_fixed vs disposition"); print(pd.crosstab(a.meeting_fixed, a.disposition_label))
print("\n== tbro fill by disposition"); print(a.groupby('disposition_label').lead_tbro_time.apply(lambda x: x.notna().mean()).round(3))
